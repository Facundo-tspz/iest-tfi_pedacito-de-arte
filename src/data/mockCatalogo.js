function crearOpciones(productoId, grupos) {
  return grupos.flatMap((grupo) =>
    OPCIONES_BASE[grupo].map((opcion) => ({
      id: `op-${productoId}-${grupo}-${opcion.orden}`,
      ...opcion,
      provisional: true,
    })),
  );
}

function crearCategoriaResumen(id) {
  const categoria = CATEGORIAS.find((item) => item.id === id);

  return {
    id: categoria.id,
    nombre: categoria.nombre,
    slug: categoria.slug,
  };
}

